'use client';

import { motion, useReducedMotion } from 'motion/react';

/**
 * Entry motion for marketing sections. It exists to sequence a reader down the
 * page, not for decoration, so it fires once and never loops. Under
 * `prefers-reduced-motion` the content renders in place with no transition.
 */
export function Reveal({
  children,
  delay = 0,
  className,
}: {
  children: React.ReactNode;
  delay?: number;
  className?: string;
}) {
  const reduce = useReducedMotion();
  return (
    <motion.div
      className={className}
      initial={reduce ? false : { opacity: 0, y: 20 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, amount: 0.25 }}
      transition={{ duration: 0.55, delay, ease: [0.16, 1, 0.3, 1] }}
    >
      {children}
    </motion.div>
  );
}
